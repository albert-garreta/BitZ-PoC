def validate_cross_inputs(
    headline: dict[str, Any], intervals: dict[str, Any]
) -> None:
    """Reject a dashboard whose clean and profiled series are not the same sweep."""

    for point, size in zip(headline["points"], intervals["sizes"], strict=True):
        exponent = point["i"]
        if size["i"] != exponent:
            raise DashboardError("headline and interval exponents are not aligned")
        for key in ("t", "s", "word_bits"):
            if point[key] != size[key]:
                raise DashboardError(
                    f"i={exponent}: headline and interval {key} values differ"
                )
        if point["requested_ligerito"] != size["requested_config"]:
            raise DashboardError(
                f"i={exponent}: headline and interval requested configs differ"
            )
        if point["resolved_ligerito"] != size["resolved_config"]:
            raise DashboardError(
                f"i={exponent}: headline and interval resolved configs differ"
            )
        if require_integer_text(point["threads"], "threads") != size["threads"]:
            raise DashboardError(
                f"i={exponent}: headline and interval thread counts differ"
            )
        if point["reps"] != size["measured_n"]:
            raise DashboardError(
                f"i={exponent}: headline reps and interval measured trials differ"
            )
        interval_proof = size["proof"]["total"]["med"]
        if point["proof_bytes"] != interval_proof:
            raise DashboardError(
                f"i={exponent}: clean and interval P50 proof bytes differ "
                f"({point['proof_bytes']} != {interval_proof})"
            )


def json_for_script(payload: dict[str, Any]) -> str:
    """Serialize JSON without permitting an embedded closing script tag."""

    serialized = json.dumps(
        payload,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    )
    return (
        serialized.replace("&", r"\u0026")
        .replace("<", r"\u003c")
        .replace(">", r"\u003e")
        .replace("\u2028", r"\u2028")
        .replace("\u2029", r"\u2029")
    )



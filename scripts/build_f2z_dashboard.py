def render_html(
    headline_payload: dict[str, Any], interval_payload: dict[str, Any]
) -> str:
    profile = escape_html_text(headline_payload["series"]["requested_config"])
    return (
        HTML_TEMPLATE.replace("__GENERATED_MARKER__", GENERATED_MARKER)
        .replace("__HEADLINE_DATA__", json_for_script(headline_payload))
        .replace("__INTERVAL_DATA__", json_for_script(interval_payload))
        .replace("__PROFILE_HTML__", profile)
    )


def write_generated(output: Path, content: str, *, adopt_existing: bool = False) -> None:
    """Atomically write output, refusing to clobber hand-authored files."""

    if output.is_symlink():
        raise DashboardError(f"refusing to replace symlink: {output}")
    if output.exists():
        try:
            prefix = output.read_text(encoding="utf-8")[:512]
        except UnicodeDecodeError as exc:
            raise DashboardError(f"refusing to replace non-text file: {output}") from exc
        if GENERATED_MARKER not in prefix and not adopt_existing:
            raise DashboardError(
                f"refusing to replace {output}: generated marker is absent; "
                "pass --adopt-existing for the intentional first replacement"
            )
        if GENERATED_MARKER not in prefix and output.suffix.lower() not in {".html", ".htm"}:
            raise DashboardError(f"refusing to adopt non-HTML destination: {output}")

    output.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{output.name}.", suffix=".tmp", dir=output.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, output)
    finally:
        temporary.unlink(missing_ok=True)


def main() -> int:
    args = parse_args()
    try:
        with args.input.open(encoding="utf-8") as handle:
            headline = validate_payload(json.load(handle))
        with args.interval_input.open(encoding="utf-8") as handle:
            intervals = validate_interval_payload(json.load(handle))
        validate_cross_inputs(headline, intervals)
        html = render_html(headline, intervals)
        write_generated(args.output, html, adopt_existing=args.adopt_existing)
    except (DashboardError, json.JSONDecodeError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

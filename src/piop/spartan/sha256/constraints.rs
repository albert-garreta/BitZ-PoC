/// Live Boolean source bits generated by one compression.
pub const SHA256_F_LIVE_BITS: usize = 7_144;
/// Source bits after adding the public constant-one coordinate.
pub const SHA256_F_BAR_LIVE_BITS: usize = SHA256_F_LIVE_BITS + 1;
/// Padded source stride used by the committed bit grid.
pub const SHA256_F_STRIDE: usize = 1 << SHA256_F_LOCAL_VARS;
/// Local source-coordinate width.
pub const SHA256_F_LOCAL_VARS: usize = 13;

/// Live integer-assignment bits, including its leading constant one.
pub const SHA256_H_BAR_LIVE_BITS: usize = 20_457;
/// Padded Spartan-assignment stride.
pub const SHA256_H_STRIDE: usize = 1 << SHA256_H_LOCAL_VARS;
/// Local assignment-coordinate width.
pub const SHA256_H_LOCAL_VARS: usize = 15;

/// Number of public words in one compression statement: state, block, output.
pub(crate) const SHA256_PUBLIC_WORDS: usize = 32;
/// Bit width of every public SHA-256 word.
pub(crate) const SHA256_PUBLIC_WORD_BITS: usize = 32;
/// Returns the local integer-assignment column for one public statement bit.
///
/// Word slots use canonical statement order: state `[0, 8)`, block `[8, 24)`,
/// then output `[24, 32)`. Bits within each word are least-significant first.
pub(crate) const fn sha256_public_h_column(word_slot: usize, bit: usize) -> usize {
    assert!(word_slot < SHA256_PUBLIC_WORDS);
    assert!(bit < SHA256_PUBLIC_WORD_BITS);

    match word_slot {
        0..8 => 1 + 32 * word_slot + bit,
        8..24 => 257 + 32 * (word_slot - 8) + bit,
        _ => 20_193 + 33 * (word_slot - 24) + bit,
    }
}

/// Returns the local committed-source column for one public statement bit.
///
/// This uses the same word and bit order as [`sha256_public_h_column`].
pub(crate) const fn sha256_public_f_column(word_slot: usize, bit: usize) -> usize {
    assert!(word_slot < SHA256_PUBLIC_WORDS);
    assert!(bit < SHA256_PUBLIC_WORD_BITS);

    match word_slot {
        0..8 => 513 + 32 * word_slot + bit,
        8..24 => 1 + 32 * (word_slot - 8) + bit,
        _ => 6_881 + 33 * (word_slot - 24) + bit,
    }
}

/// Live rank-1 constraints generated by one compression.
pub const SHA256_CONSTRAINTS: usize = 184;
/// Padded constraint-row stride.
pub const SHA256_CONSTRAINT_STRIDE: usize = 1 << SHA256_CONSTRAINT_LOCAL_VARS;
/// Local constraint-row coordinate width.
pub const SHA256_CONSTRAINT_LOCAL_VARS: usize = 8;

/// Failures while compiling or repeating the public SHA-256 relation.
#[derive(Debug, Error)]
pub enum Sha256ConstraintError {
    /// The requested power-of-two batch does not fit the host index type.
    #[error("SHA-256 compression exponent is too large")]
    InvalidBatchExponent,

    /// Generated R1CS matrices did not prepare successfully.
    #[error(transparent)]
    Spartan(#[from] SpartanMatrixError),

    /// Generated Boolean map metadata did not prepare successfully.
    #[error(transparent)]
    VirtualMap(#[from] PreparedVirtualMapError),

    /// The canonical integer-relation digest cannot encode this host shape.
    #[error("SHA-256 integer relation dimensions do not fit the canonical encoding")]
    IntegerRelationTooLarge,

    /// The security profile could not be instantiated at this shape.
    #[error(transparent)]
    Profile(#[from] ProfileError),
}

/// A q-independent SHA-256 compression relation prepared for a power-of-two
/// batch.
///
/// The exact signed integer matrices and local Boolean map are synthesized
/// once and shared by every batch. Only the inexpensive repetition metadata
/// depends on `log_compressions`. Calling [`Self::project`] is the explicit
/// boundary at which a transcript-selected runtime prime becomes visible.
#[derive(Clone, Debug)]
pub struct PreparedSha256CompressionBatch {
    local: &'static IntegerLocalRelation,
    map: RepeatedVirtualMap,
    p_f: IntEvalParams,
    p_h: IntEvalParams,
    security: IopSecurityParams,
}

impl PreparedSha256CompressionBatch {
    /// Projects the exact signed coefficients into a validated runtime prime
    /// field. The q-independent relation and its digest remain unchanged.
    pub fn project(
        &self,
        field_config: &<F128 as PrimeField>::Config,
    ) -> Result<PreparedConstraintMatrices<SpartanF2zField>, Sha256ConstraintError> {
        project_integer_relation(&self.local.matrices, field_config)
    }

    /// Canonical digest of the exact integer matrices and local Boolean map.
    pub const fn integer_relation_digest(&self) -> &[u8; 32] {
        &self.local.digest
    }

    /// Repeated Boolean map for the complete compression batch.
    pub const fn map(&self) -> &RepeatedVirtualMap {
        &self.map
    }

    /// F2Z geometry of the committed Boolean source rows.
    pub const fn source_params(&self) -> &IntEvalParams {
        &self.p_f
    }

    /// F2Z geometry of the synthesized integer-assignment rows.
    pub const fn assignment_params(&self) -> &IntEvalParams {
        &self.p_h
    }

    /// Conservative maximum of
    /// `sum(|A_i|) sum(|B_i|) + sum(|C_i|)` over local constraint rows.
    /// For a Boolean assignment this bounds the magnitude of every exact
    /// integer R1CS residual before reduction modulo q.
    pub fn max_boolean_residual_bound(&self) -> &BigUint {
        &self.local.max_boolean_residual_bound
    }

    /// The instantiated security parameters and their accounting.
    pub const fn security(&self) -> &IopSecurityParams {
        &self.security
    }
}

#[derive(Debug)]
struct IntegerLocalRelation {
    matrices: ConstraintMatrices<BigInt>,
    map: PreparedVirtualMap,
    digest: [u8; 32],
    max_boolean_residual_bound: BigUint,
}

static INTEGER_LOCAL_RELATION: OnceLock<IntegerLocalRelation> = OnceLock::new();

/// Prepares the q-independent public relation for
/// `2^log_compressions` independent SHA-256 compression invocations at the
/// DEFAULT security profile, [`Lambda100`] (no grinding anywhere; every
/// term this crate controls ≥ 100 bits). Use
/// [`prepare_sha256_compression_batch_integer_with_profile`] to select
/// `Lambda128` or the historical `LegacySha128Design` schedule.
///
/// No runtime modulus is consulted here. The caller must commit to the
/// Boolean source rows before deriving q and invoking [`PreparedSha256CompressionBatch::project`].
pub fn prepare_sha256_compression_batch_integer(
    log_compressions: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    prepare_sha256_compression_batch_integer_with_profile::<Lambda100>(log_compressions)
}

/// [`prepare_sha256_compression_batch_integer`] under an explicit
/// single-prime security profile: the profile's interval and grinding
/// schedule are instantiated here and drive the whole prove/verify path.
pub fn prepare_sha256_compression_batch_integer_with_profile<P: IopSecurityProfile>(
    log_compressions: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    let instances = validate_batch_exponent(log_compressions)?;
    let exponent = u32::try_from(log_compressions)
        .map_err(|_| Sha256ConstraintError::InvalidBatchExponent)?;
    let security = P::instantiate(&sha256_instance_facts(exponent))?;
    let local = integer_local_relation();
    let map = RepeatedVirtualMap::new(local.map.clone(), instances)?;
    let p_f = IntEvalParams {
        t: log_compressions,
        s: SHA256_F_LOCAL_VARS,
        word_bits: 1,
    };
    let p_h = IntEvalParams {
        t: log_compressions,
        s: SHA256_H_LOCAL_VARS,
        word_bits: 1,
    };
    Ok(PreparedSha256CompressionBatch {
        local,
        map,
        p_f,
        p_h,
        security,
    })
}

/// Prepares the public relation for `2^log_compressions` independent SHA-256
/// compression invocations.
///
/// The returned Spartan matrices are the one-compression local matrices. The
/// batch repetition is implicit in the returned map and in the two F2Z
/// geometries; the SHA proof adapter applies the same tensor structure to the
/// local `A/B/C` matrices without materializing global CSC offsets.
pub fn prepare_sha256_compression_batch(
    log_compressions: usize,
) -> Result<
    (
        PreparedConstraintMatrices<SpartanF2zField>,
        RepeatedVirtualMap,
        IntEvalParams,
        IntEvalParams,
    ),
    Sha256ConstraintError,
> {
    let prepared = prepare_sha256_compression_batch_integer(log_compressions)?;
    let matrices = prepared.project(&spartan_f2z_field_config())?;
    Ok((matrices, prepared.map, prepared.p_f, prepared.p_h))
}

fn validate_batch_exponent(log_compressions: usize) -> Result<usize, Sha256ConstraintError> {
    let instances = 1usize
        .checked_shl(
            u32::try_from(log_compressions)
                .map_err(|_| Sha256ConstraintError::InvalidBatchExponent)?,
        )
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    SHA256_H_STRIDE
        .checked_mul(instances)
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    Ok(instances)
}

fn integer_local_relation() -> &'static IntegerLocalRelation {
    INTEGER_LOCAL_RELATION.get_or_init(|| {
        build_integer_local_relation().expect("the static SHA-256 compression relation is valid")
    })
}

fn build_integer_local_relation() -> Result<IntegerLocalRelation, Sha256ConstraintError> {
    let mut generator = ConstraintGenerator::new(COMPRESSION_INPUT_BITS);
    let inputs = generator.inputs();
    let output = compression_circuit(&mut generator, &inputs);
    let generated = generator.into_matrices();

    assert_eq!(generated.m.row_count(), SHA256_H_BAR_LIVE_BITS);
    assert_eq!(generated.m.column_count(), SHA256_F_BAR_LIVE_BITS);
    assert_eq!(generated.a.row_count(), SHA256_CONSTRAINTS);
    assert_eq!(generated.b.row_count(), SHA256_CONSTRAINTS);
    assert_eq!(generated.c.row_count(), SHA256_CONSTRAINTS);
    assert_eq!(generated.a.column_count(), SHA256_H_BAR_LIVE_BITS);
    assert_eq!(generated.m.rows()[0].positions(), &[0]);

    for word_slot in 0..SHA256_PUBLIC_WORDS {
        for bit in 0..SHA256_PUBLIC_WORD_BITS {
            let h_column = sha256_public_h_column(word_slot, bit);
            let f_column = sha256_public_f_column(word_slot, bit);
            assert_eq!(generated.m.rows()[h_column].positions(), &[f_column]);

            if word_slot >= 24 {
                let output_bit = &output[(word_slot - 24) * SHA256_PUBLIC_WORD_BITS + bit];
                assert!(!output_bit.constant());
                assert_eq!(output_bit.witnesses().len(), 1);
                assert!(output_bit.witnesses().contains(&(f_column - 1)));
            }
        }
    }

    let a = convert_integer_matrix(&generated.a)?;
    let b = convert_integer_matrix(&generated.b)?;
    let c = convert_integer_matrix(&generated.c)?;
    let matrices = ConstraintMatrices::new(a, b, c)?;

    let mut map_rows = generated
        .m
        .rows()
        .iter()
        .map(|row| {
            row.positions()
                .iter()
                .copied()
                .map(|column| (column, true))
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    map_rows.resize_with(SHA256_H_STRIDE, Vec::new);
    let map =
        SparseMatrix::try_from_rows(SHA256_F_STRIDE, map_rows).map_err(SpartanMatrixError::from)?;
    let map = PreparedVirtualMap::new(map)?;
    let max_boolean_residual_bound = max_boolean_residual_bound(&matrices);
    let digest = integer_relation_digest(&matrices, &map)?;

    Ok(IntegerLocalRelation {
        matrices,
        map,
        digest,
        max_boolean_residual_bound,
    })
}

fn convert_integer_matrix(
    matrix: &CircuitSparseMatrix<BigInt>,
) -> Result<SparseMatrix<BigInt>, SpartanMatrixError> {
    debug_assert!(matrix.row_count() <= SHA256_CONSTRAINT_STRIDE);
    debug_assert!(matrix.column_count() <= SHA256_H_STRIDE);

    let mut rows = matrix
        .rows()
        .iter()
        .map(|row| {
            row.entries()
                .iter()
                .map(|(column, coefficient)| (*column, coefficient.clone()))
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    rows.resize_with(SHA256_CONSTRAINT_STRIDE, Vec::new);
    SparseMatrix::try_from_rows(SHA256_H_STRIDE, rows).map_err(SpartanMatrixError::from)
}

fn project_integer_relation(
    matrices: &ConstraintMatrices<BigInt>,
    field_config: &<F128 as PrimeField>::Config,
) -> Result<PreparedConstraintMatrices<SpartanF2zField>, Sha256ConstraintError> {
    <SpartanF2zField as SpartanField>::validate_config(field_config)
        .map_err(SpartanMatrixError::from)?;
    let modulus = BigInt::from(BigUint::from_bytes_le(
        &SpartanF2zField::canonical_modulus_encoding(field_config),
    ));
    let project =
        |matrix: &SparseMatrix<BigInt>| -> Result<SparseMatrix<F128>, SpartanMatrixError> {
            let columns = matrix
                .columns()
                .map(|column| {
                    column
                        .into_iter()
                        .map(|(row, coefficient)| {
                            (row, bigint_to_field(coefficient, &modulus, field_config))
                        })
                        .collect::<Vec<_>>()
                })
                .collect::<Vec<_>>();
            SparseMatrix::try_from_columns(matrix.row_count(), columns)
                .map_err(SpartanMatrixError::from)
        };
    let matrices = ConstraintMatrices::new(
        project(matrices.a())?,
        project(matrices.b())?,
        project(matrices.c())?,
    )?;
    PreparedConstraintMatrices::new(matrices, field_config).map_err(Sha256ConstraintError::from)
}

fn bigint_to_field(
    value: &BigInt,
    modulus: &BigInt,
    field_config: &<F128 as PrimeField>::Config,
) -> F128 {
    let mut reduced = value % modulus;
    if reduced.sign() == Sign::Minus {
        reduced += modulus;
    }
    let words = reduced
        .to_biguint()
        .expect("a reduced coefficient is nonnegative")
        .to_u64_digits();
    let canonical = Uint::new(
        [
            words.first().copied().unwrap_or(0),
            words.get(1).copied().unwrap_or(0),
        ]
        .into(),
    );
    F128::new_with_cfg(canonical, field_config)
}

fn max_boolean_residual_bound(matrices: &ConstraintMatrices<BigInt>) -> BigUint {
    let row_sums = |matrix: &SparseMatrix<BigInt>| {
        let mut sums = vec![BigUint::default(); matrix.row_count()];
        for column in matrix.columns() {
            for (row, coefficient) in column {
                sums[row] += coefficient.magnitude();
            }
        }
        sums
    };
    let a = row_sums(matrices.a());
    let b = row_sums(matrices.b());
    let c = row_sums(matrices.c());
    a.into_iter()
        .zip(b)
        .zip(c)
        .map(|((a, b), c)| a * b + c)
        .max()
        .unwrap_or_default()
}

fn integer_relation_digest(
    matrices: &ConstraintMatrices<BigInt>,
    map: &PreparedVirtualMap,
) -> Result<[u8; 32], Sha256ConstraintError> {
    let mut hash = Hasher::new();
    hash.update(b"f2z/sha256/integer-relation/v1");
    hash.update(&map.digest());
    for (label, matrix) in
        [b'A', b'B', b'C']
            .into_iter()
            .zip([matrices.a(), matrices.b(), matrices.c()])
    {
        hash.update(&[label]);
        for value in [matrix.row_count(), matrix.column_count(), matrix.nnz()] {
            hash_usize(&mut hash, value)?;
        }
        for column in matrix.columns() {
            hash_usize(&mut hash, column.len())?;
            for (row, coefficient) in column {
                hash_usize(&mut hash, row)?;
                let (sign, magnitude) = coefficient.to_bytes_le();
                hash.update(&[match sign {
                    Sign::NoSign => 0,
                    Sign::Plus => 1,
                    Sign::Minus => 2,
                }]);
                hash_usize(&mut hash, magnitude.len())?;
                hash.update(&magnitude);
            }
        }
    }
    Ok(*hash.finalize().as_bytes())
}

fn hash_usize(hash: &mut Hasher, value: usize) -> Result<(), Sha256ConstraintError> {
    hash.update(
        &u64::try_from(value)
            .map_err(|_| Sha256ConstraintError::IntegerRelationTooLarge)?
            .to_le_bytes(),
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use crypto_primitives::crypto_bigint_uint::Uint;

    use crate::f2map::VirtualMap;
    use crate::pcs::FQ_MOD;

    use super::*;

    const OTHER_TEST_PRIME: u128 = (1_u128 << 127) - 1;

    fn config(modulus: u128) -> <F128 as PrimeField>::Config {
        F128::make_cfg(&Uint::from(modulus)).expect("odd test modulus")
    }

    #[test]
    fn local_relation_has_the_freigen_geometry() {
        let (matrices, map, p_f, p_h) = prepare_sha256_compression_batch(3).unwrap();
        assert_eq!(
            matrices.matrices().a().row_count(),
            SHA256_CONSTRAINT_STRIDE
        );
        assert_eq!(matrices.matrices().a().column_count(), SHA256_H_STRIDE);
        assert_eq!(matrices.num_row_vars(), SHA256_CONSTRAINT_LOCAL_VARS);
        assert_eq!(matrices.num_column_vars(), SHA256_H_LOCAL_VARS);
        assert_eq!(map.local().rows(), SHA256_H_STRIDE);
        assert_eq!(map.local().cols(), SHA256_F_STRIDE);
        assert_eq!(map.rows(), 8 * SHA256_H_STRIDE);
        assert_eq!(map.cols(), 8 * SHA256_F_STRIDE);
        assert_eq!(
            p_f,
            IntEvalParams {
                t: 3,
                s: 13,
                word_bits: 1
            }
        );
        assert_eq!(
            p_h,
            IntEvalParams {
                t: 3,
                s: 15,
                word_bits: 1
            }
        );
    }

    #[test]
    fn repeated_map_preserves_instance_coordinates() {
        let (_, map, _, _) = prepare_sha256_compression_batch(2).unwrap();
        let instances = 4;
        for local_column in [0, 1, SHA256_F_BAR_LIVE_BITS - 1] {
            let local_rows = map
                .local()
                .matrix()
                .column(local_column)
                .unwrap()
                .row_indices()
                .to_vec();
            for instance in 0..instances {
                let global_column = local_column * instances + instance;
                let global_rows = map.column_rows(global_column).unwrap().collect::<Vec<_>>();
                assert_eq!(
                    global_rows,
                    local_rows
                        .iter()
                        .map(|row| row * instances + instance)
                        .collect::<Vec<_>>()
                );
            }
        }
    }

    #[test]
    fn public_statement_layout_matches_the_local_map() {
        let (_, map, _, _) = prepare_sha256_compression_batch(0).unwrap();
        let mut sources_by_h = vec![Vec::new(); map.local().matrix().row_count()];
        for (f_column, column) in map.local().matrix().columns().enumerate() {
            for &h_column in column.row_indices() {
                sources_by_h[h_column].push(f_column);
            }
        }

        for word_slot in 0..SHA256_PUBLIC_WORDS {
            for bit in 0..SHA256_PUBLIC_WORD_BITS {
                let h_column = sha256_public_h_column(word_slot, bit);
                let f_column = sha256_public_f_column(word_slot, bit);
                assert_eq!(sources_by_h[h_column], [f_column]);
            }
        }
    }

    #[test]
    fn integer_relation_projects_under_distinct_runtime_primes() {
        let prepared = prepare_sha256_compression_batch_integer(3).unwrap();
        let fixed_config = config(FQ_MOD);
        let other_config = config(OTHER_TEST_PRIME);
        let fixed = prepared.project(&fixed_config).unwrap();
        let other = prepared.project(&other_config).unwrap();

        assert_eq!(
            fixed.field_modulus_encoding(),
            F128::canonical_modulus_encoding(&fixed_config)
        );
        assert_eq!(
            other.field_modulus_encoding(),
            F128::canonical_modulus_encoding(&other_config)
        );
        assert_ne!(fixed.digest(), other.digest());

        for (raw, fixed_matrix, other_matrix) in [
            prepared.local.matrices.a(),
            prepared.local.matrices.b(),
            prepared.local.matrices.c(),
        ]
        .into_iter()
        .zip([
            fixed.matrices().a(),
            fixed.matrices().b(),
            fixed.matrices().c(),
        ])
        .zip([
            other.matrices().a(),
            other.matrices().b(),
            other.matrices().c(),
        ])
        .map(|((raw, fixed), other)| (raw, fixed, other))
        {
            for ((raw_column, fixed_column), other_column) in raw
                .columns()
                .zip(fixed_matrix.columns())
                .zip(other_matrix.columns())
            {
                assert_eq!(raw_column.row_indices(), fixed_column.row_indices());
                assert_eq!(raw_column.row_indices(), other_column.row_indices());
                for ((raw_coefficient, fixed_coefficient), other_coefficient) in raw_column
                    .coefficients()
                    .iter()
                    .zip(fixed_column.coefficients())
                    .zip(other_column.coefficients())
                {
                    assert_eq!(
                        fixed_coefficient,
                        &bigint_to_field(raw_coefficient, &BigInt::from(FQ_MOD), &fixed_config,)
                    );
                    assert_eq!(
                        other_coefficient,
                        &bigint_to_field(
                            raw_coefficient,
                            &BigInt::from(OTHER_TEST_PRIME),
                            &other_config,
                        )
                    );
                }
            }
        }

        let same_relation = prepare_sha256_compression_batch_integer(0).unwrap();
        assert_eq!(
            prepared.integer_relation_digest(),
            same_relation.integer_relation_digest()
        );
    }

    #[test]
    fn boolean_residual_bound_is_below_the_smallest_production_prime() {
        let prepared = prepare_sha256_compression_batch_integer(0).unwrap();
        assert!(prepared.max_boolean_residual_bound() < &(BigUint::from(1_u8) << 111));
    }
}
